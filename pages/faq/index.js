  onSearchInput: function(e) { this.setData({ searchKeyword: e.detail }); this.filterFaq(); },
  onToggleSearch: function() { this.setData({ showSearch: !this.data.showSearch }); },

  onCategoryTap: function(e) {
    this.setData({ activeCategory: e.currentTarget.dataset.category });
    this.filterFaq();
  },

  filterFaq: function() {
    var list = this.data.faqList;
    var cat = this.data.activeCategory;
    var keyword = this.data.searchKeyword.trim().toLowerCase();
    if (cat !== "全部") { list = list.filter(function(f) { return f.category === cat; }); }
    if (keyword) { list = list.filter(function(f) { return f.question.toLowerCase().includes(keyword) || f.tags.some(function(t) { return t.toLowerCase().includes(keyword); }); }); }
    this.setData({ filteredList: list });
  },

  onItemTap: function(e) {
    var id = e.currentTarget.dataset.id;
    var item = this.data.faqList.find(function(f) { return f.id === id; });
    if (item) {
      wx.setStorageSync("currentFaqItem", item);
      wx.navigateTo({ url: "/pages/faq/detail" });
    }
  }
